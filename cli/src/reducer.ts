const slices = [navigationReducer, settingsReducer, consoleReducer, chatReducer];

/** Root composition keeps the public reducer API stable while slices own their actions. */
export function reducer(state: AppState, action: AppAction): AppState {
  for (const slice of slices) {
    const next = slice(state, action);
    if (next) return next;
  }
  return state;
}
